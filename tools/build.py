"""Build the app's data and offline cache.

1. app/catalog.js (+ catalog.json for tools) from data/kits.json + data/motors.json.
   Checks every recommended engine against the motor data so a typo in kits.json
   fails here rather than in the field.
2. Stamps app/sw.js with a hash of the app files, so installed copies pick up
   the new version next time they're online.

Run after any change to data/ or app/:

    python3 tools/build.py
"""
import hashlib
import json
import re
from pathlib import Path

from sim import parse_engine

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"


def main():
    kits = json.loads((ROOT / "data" / "kits.json").read_text())["kits"]
    motors = json.loads((ROOT / "data" / "motors.json").read_text())
    errors = []
    for kit in kits:
        opts = kit.get("recovery_options")
        if opts:
            first = {k: v for k, v in opts[0].items() if k not in ("id", "name", "mass_delta_g")}
            if first != kit["recovery"] or opts[0].get("mass_delta_g", 0) != 0:
                errors.append(f"{kit['id']}: first recovery option must match recovery, with no mass change")
        for cfg in kit["configs"]:
            for i, st in enumerate(cfg["stages"]):
                booster = i < len(cfg["stages"]) - 1
                if booster and "mass_g" not in st:
                    errors.append(f"{kit['id']}/{cfg['id']}: booster stage needs mass_g")
                for code in st["engines"]:
                    name, delay = parse_engine(code)
                    if name not in motors:
                        errors.append(f"{kit['id']}: no motor data for {code}")
                        continue
                    delays = motors[name]["delays"].split(",")
                    if f"{delay:g}" not in delays:
                        errors.append(f"{kit['id']}: {code} — ThrustCurve lists delays {motors[name]['delays']}")
                    if booster != (delay == 0):
                        errors.append(f"{kit['id']}/{cfg['id']}: {code} is in the wrong stage")
    if errors:
        raise SystemExit("\n".join(errors))
    # every motor ships, not just recommended ones: the app can offer others that fit the mount
    out = {"kits": kits, "motors": motors}
    data = json.dumps(out, separators=(",", ":"))
    (APP / "catalog.json").write_text(data + "\n")
    (APP / "catalog.js").write_text(f"// Generated by tools/build.py — edit data/ instead.\nself.CATALOG = {data};\n")
    print(f"wrote app/catalog.js: {len(kits)} kits, {len(out['motors'])} motors")
    stamp_sw()


def stamp_sw():
    sw = APP / "sw.js"
    files = re.search(r"const FILES = (\[.*?\]);", sw.read_text(), re.S).group(1)
    h = hashlib.sha256()
    for name in json.loads(files):
        name = "index.html" if name == "./" else name
        h.update((APP / name).read_bytes())
    version = h.hexdigest()[:10]
    text = re.sub(r'const VERSION = "[^"]*";', f'const VERSION = "{version}";', sw.read_text())
    sw.write_text(text)
    print(f"stamped app/sw.js version {version}")


if __name__ == "__main__":
    main()
